local autoMount = EventCallback("OtsAutoMountOnChangeZone")

function autoMount.playerOnChangeZone(player, zone)
	if zone == ZONE_PROTECTION then
		return
	end
	local outfit = player:getOutfit()
	if not outfit or (outfit.lookMount or 0) ~= 0 then
		return
	end
	if player:getCondition(CONDITION_OUTFIT) then
		return
	end
	local id = tonumber(player:kv():get("last-mount")) or 0
	local mount = mounts[id]
	if not mount or not player:hasMount(id) then
		return
	end
	outfit.lookMount = mount[1]
	player:setOutfit(outfit)
	if mount[2] > 0 then
		player:changeSpeed(mount[2])
	end
end

autoMount:register()
